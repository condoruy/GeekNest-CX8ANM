#!/usr/bin/env python3
"""Generate LovyanGFX GFXfont C++ sources (1-bit) from TrueType fonts.

Covers Latin-1 (ñ, á, ¿, ¡, º...) plus common typographic punctuation, euro,
degree and play/stop symbols, so Spanish stream titles render correctly.

usage: make_gfxfont.py <output.cpp> <output.h>
Uses DejaVu Sans (Bitstream Vera license) from /usr/share/fonts/truetype/dejavu.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

DEJAVU = "/usr/share/fonts/truetype/dejavu/"
FONTS = [  # (C name, ttf, pixel size)
    ("cx8_sans12", DEJAVU + "DejaVuSansCondensed.ttf", 12),
    ("cx8_sans16", DEJAVU + "DejaVuSansCondensed.ttf", 15),
    ("cx8_sans16b", DEJAVU + "DejaVuSansCondensed-Bold.ttf", 15),
    ("cx8_sans24b", DEJAVU + "DejaVuSansCondensed-Bold.ttf", 22),
]
RANGES = [(0x20, 0xFF), (0x2013, 0x2014), (0x2018, 0x201E), (0x2022, 0x2022), (0x2026, 0x2026),
          (0x20AC, 0x20AC), (0x25A0, 0x25A0), (0x25B6, 0x25B6), (0x266A, 0x266B)]


def glyph(font, ch):
    advance = int(round(font.getlength(ch)))
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    w, h = max(0, right - left), max(0, bottom - top)
    bits = []
    if w and h and not ch.isspace():
        img = Image.new("1", (w, h), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((-left, -top), ch, font=font, fill=1, anchor="ls")
        px = img.load()
        bits = [1 if px[x, y] else 0 for y in range(h) for x in range(w)]
    else:
        w = h = 0
    data = bytearray()
    for i in range(0, len(bits), 8):
        b = 0
        for j, bit in enumerate(bits[i:i + 8]):
            b |= bit << (7 - j)
        data.append(b)
    return data, w, h, advance, left, top


def build(name, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs, ranges, index = [], [], 0
    for start, end in RANGES:
        ranges.append((start, end, index))
        for code in range(start, end + 1):
            data, w, h, adv, xo, yo = glyph(font, chr(code))
            glyphs.append((len(bitmap), w, h, adv, xo, yo))
            bitmap += data
            index += 1
    out = []
    out.append("static const uint8_t %s_bitmap[] PROGMEM = {" % name)
    for i in range(0, len(bitmap), 24):
        out.append("  " + ",".join("0x%02X" % b for b in bitmap[i:i + 24]) + ",")
    out.append("};")
    out.append("static const lgfx::GFXglyph %s_glyphs[] PROGMEM = {" % name)
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append("static const lgfx::EncodeRange %s_ranges[] PROGMEM = {" % name)
    for r in ranges:
        out.append("  {0x%04X,0x%04X,%d}," % r)
    out.append("};")
    out.append("const lgfx::GFXfont %s((uint8_t*)%s_bitmap, (lgfx::GFXglyph*)%s_glyphs, 0x%04X, 0x%04X, %d, %d, (lgfx::EncodeRange*)%s_ranges);"
               % (name, name, name, RANGES[0][0], RANGES[-1][1], ascent + descent, len(ranges), name))
    return "\n".join(out), len(bitmap) + 12 * len(glyphs)


def main():
    cpp = ["// Generated by tools/make_gfxfont.py from DejaVu Sans Condensed (Bitstream Vera license).",
           '#include "fonts_cx8.h"', ""]
    h = ["#pragma once", "// Latin-1 bitmap fonts for the CX8ANM screens (generated).", "#include <LovyanGFX.hpp>"]
    for name, path, size in FONTS:
        code, nbytes = build(name, path, size)
        print("%s: %d bytes" % (name, nbytes))
        cpp += [code, ""]
        h.append("extern const lgfx::GFXfont %s;" % name)
    open(sys.argv[1], "w").write("\n".join(cpp))
    open(sys.argv[2], "w").write("\n".join(h) + "\n")


if __name__ == "__main__":
    main()

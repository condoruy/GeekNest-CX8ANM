#!/usr/bin/env python3
"""Subset LovyanGFX's efont (U8g2 format) to Latin/Greek/Cyrillic and symbols.

The full CJK efont fonts take about 1.1 MB of flash; the subset keeps the exact
same glyphs and metrics for the characters used in Uruguay/Latin America (RDS,
ICY titles, Spanish UI), so the screen looks the same and two firmware copies
fit in flash for over-the-air updates.

usage: subset_efont.py <path to LovyanGFX Fonts/efont/lgfx_efont_cn.c> <output .c>
"""
import re
import sys

FONTS = [("lgfx_efont_cn_24_b", "cx8_efont_24_b_data")]  # the font tinyradio's UI uses

KEEP = [(0x0100, 0x024F),   # Latin Extended A/B
        (0x0370, 0x03FF),   # Greek
        (0x0400, 0x04FF),   # Cyrillic
        (0x1E00, 0x1EFF),   # Latin Extended Additional
        (0x2000, 0x206F),   # General punctuation: dashes, quotes, bullet, ellipsis
        (0x20A0, 0x20CF),   # Currency (euro)
        (0x2100, 0x214F),   # Letterlike (degree Celsius, trademark)
        (0x2190, 0x21FF),   # Arrows
        (0x2200, 0x22FF),   # Math operators
        (0x2500, 0x25FF),   # Box drawing, blocks, geometric shapes
        (0x2600, 0x26FF)]   # Misc symbols (music notes, stars)


def keep(code):
    return any(lo <= code <= hi for lo, hi in KEEP)


def decode_c_string(body):
    out = bytearray()
    i = 0
    while i < len(body):
        c = body[i]
        if c != "\\":
            out.append(ord(c)); i += 1; continue
        n = body[i + 1]
        if n in "01234567":
            j = i + 1
            while j < len(body) and j < i + 4 and body[j] in "01234567":
                j += 1
            out.append(int(body[i + 1:j], 8)); i = j
        elif n == "x":
            j = i + 2
            while j < len(body) and body[j] in "0123456789abcdefABCDEF":
                j += 1
            out.append(int(body[i + 2:j], 16) & 0xFF); i = j
        else:
            out.append({"n": 10, "t": 9, "r": 13, "a": 7, "b": 8, "f": 12, "v": 11,
                        "\\": 92, "'": 39, '"': 34, "?": 63}[n]); i += 2
    return bytes(out)


def extract(source, name):
    m = re.search(r"const uint8_t " + name + r"\[(\d+)\]\s*=\s*", source)
    if not m:
        raise SystemExit("font %s not found" % name)
    size = int(m.group(1))
    literal = re.compile(r'\s*"((?:[^"\\]|\\.)*)"', re.S)
    literals, pos = [], m.end()
    while True:
        lm = literal.match(source, pos)
        if not lm:
            break
        literals.append(lm.group(1)); pos = lm.end()
    data = b"".join(decode_c_string(s) for s in literals) + b"\0"  # implicit NUL of the literal
    if len(data) != size:
        raise SystemExit("%s: decoded %d bytes, expected %d" % (name, len(data), size))
    return data


def subset(font):
    header = bytearray(font[:23])
    start_unicode = 23 + (font[21] << 8 | font[22])
    ascii_part = font[23:start_unicode]
    # Skip the unicode jump table: entries of 4 bytes up to unicode 0xFFFF.
    lut = start_unicode
    pos = lut
    while True:
        offset = font[pos] << 8 | font[pos + 1]
        last = font[pos + 2] << 8 | font[pos + 3]
        pos += 4
        if last == 0xFFFF:
            break
    # First glyph follows the first jump-table offset.
    glyph = lut + (font[lut] << 8 | font[lut + 1])
    kept = bytearray()
    total = count = 0
    while True:
        code = font[glyph] << 8 | font[glyph + 1]
        if code == 0:
            break
        size = font[glyph + 2]
        total += 1
        if keep(code):
            kept += font[glyph:glyph + size]
            count += 1
        glyph += size
    unicode_part = bytes([0, 4, 0xFF, 0xFF]) + kept + b"\0\0"
    return bytes(header) + ascii_part + unicode_part, count, total


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    return "extern const uint8_t %s[%d];\nPROGMEM const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(data), name, len(data), "\n".join(lines))


def main():
    source = open(sys.argv[1], encoding="latin-1").read()
    out = ["// Generated by tools/subset_efont.py from LovyanGFX efont (efont license, see COPYRIGHT).",
           "// Latin, Greek, Cyrillic and symbols only; glyphs and metrics unchanged.",
           "#include <stdint.h>", "#include <pgmspace.h>", ""]
    for src, dst in FONTS:
        font = extract(source, src)
        data, count, total = subset(font)
        print("%s: %d -> %d bytes, kept %d of %d unicode glyphs" % (src, len(font), len(data), count, total))
        out.append(c_array(dst, data))
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
